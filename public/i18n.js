export let language = "pt";
export const locale =
  () => ({ pt: "pt-BR", en: "en-US", es: "es-ES" }[language]);
export function t(text, values = {}) {
  const dynamic = text.match(
    /^O CNAME tem (\d+) caracteres; o DNS permite até 253\. Encurte a URL ou os valores UTM\.$/,
  );
  if (dynamic) {
    text =
      "O CNAME tem {count} caracteres; o DNS permite até 253. Encurte a URL ou os valores UTM.";
    values = { count: dynamic[1] };
  }
  let translated = language === "pt"
    ? text
    : messages[text]?.[language === "en" ? 0 : 1] || text;
  for (const [key, value] of Object.entries(values)) {
    translated = translated.replaceAll(`{${key}}`, String(value));
  }
  return translated;
}

export function initLanguage(onChange) {
  const originals = [];
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (
      node.parentElement.closest(
        "script,style,svg,code,pre,noscript,#language,[data-no-translate]",
      )
    ) continue;
    const original = node.textContent;
    if (original.trim()) originals.push({ node, original });
  }
  const attributes = [];
  for (
    const node of document.querySelectorAll(
      "[placeholder],[aria-label],[title]",
    )
  ) {
    for (const key of ["placeholder", "aria-label", "title"]) {
      if (node.hasAttribute(key)) {
        attributes.push({ node, key, original: node.getAttribute(key) });
      }
    }
  }
  function setLanguage(next) {
    language = ["pt", "en", "es"].includes(next) ? next : "pt";
    document.documentElement.lang = locale();
    document.body.dataset.language = language;
    document.getElementById("language").value = language;
    for (const { node, original } of originals) {
      node.textContent = original.replace(original.trim(), t(original.trim()));
    }
    for (const { node, key, original } of attributes) {
      node.setAttribute(key, t(original));
    }
    document.title = `${
      document.querySelector(".brand").textContent.trim().replace(/\.$/, "")
    } — ${t("Seu domínio, na direção certa")}.`;
    try {
      localStorage.setItem("desvio-language", language);
    } catch { /* Storage may be unavailable in private browsing. */ }
    onChange();
  }
  let saved;
  try {
    saved = localStorage.getItem("desvio-language") ||
      localStorage.getItem("lang");
  } catch { /* Use browser language. */ }
  document.getElementById("language").addEventListener(
    "change",
    (event) => setLanguage(event.target.value),
  );
  const detected = (navigator.language || "pt").slice(0, 2);
  setLanguage(
    saved || (["pt", "en", "es"].includes(detected) ? detected : "en"),
  );
}
